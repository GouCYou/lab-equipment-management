import { describe, it, expect } from "vitest";
import { relativeDate } from "./time";
const now = new Date("2026-11-08T10:30:00+08:00");
describe("北京时间相对时间", () => {
  it.each([
    ["2026-11-08T01:51:00Z", "09:51"],
    ["2026-11-07T23:59:00+08:00", "昨天"],
    ["2026-11-06T12:00:00+08:00", "前天"],
    ["2026-11-05T12:00:00+08:00", "3天前"],
    ["2026-11-01T12:00:00+08:00", "7天前"],
    ["2026-10-31T12:00:00+08:00", "10/31 12:00"],
    ["2025-11-07T12:00:00+08:00", "2025/11/07 12:00"],
    ["2026-11-09T12:00:00+08:00", "11/09 12:00"],
  ])("%s 显示 %s", (value, label) => {
    expect(relativeDate(value, true, now)).toBe(label);
  });
  it("跨 UTC 日期按北京时间判断今天", () => {
    expect(relativeDate("2026-11-07T16:01:00Z", true, now)).toBe("00:01");
  });
});
